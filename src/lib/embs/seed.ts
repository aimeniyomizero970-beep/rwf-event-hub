function tiers(reg: [number, number, number], vip: [number, number, number], vvip?: [number, number, number]) {
  const list = [
    { id: "t-reg", name: "Regular", price: reg[0], capacity: reg[1], sold: reg[2] },
    { id: "t-vip", name: "VIP", price: vip[0], capacity: vip[1], sold: vip[2] },
  ];
  if (vvip) list.push({ id: "t-vvip", name: "VVIP", price: vvip[0], capacity: vvip[1], sold: vvip[2] });
  return list;
}

